#!/usr/bin/env python3
"""Turn a cmd.exe `set` dump into a bash sourceable MSVC environment snapshot.

Used by build.sh.  The dump is what `vcvars64.bat` leaves behind; we keep only
the variables a C++ build actually needs and rebuild PATH ourselves so the
snapshot stays small and does not inherit whatever the shell had.

Usage:
    gen_msvc_env_sh.py <dump.txt> <out.sh> <vsinst> <msvc_version>
"""
import re
import sys

# Variables that carry absolute paths baked with the toolchain version.
# They are exactly the ones that go stale when VS or the Windows SDK moves.
KEEP = [
    "INCLUDE", "LIB", "LIBPATH",
    "VCToolsInstallDir", "WindowsSdkDir", "WindowsSDKVersion",
    "WindowsSdkBinPath", "WindowsSdkVerBinPath",
    "UniversalCRTSdkDir", "UCRTVersion",
    "VSINSTALLDIR", "VisualStudioVersion",
]


def parse_dump(path):
    pairs = {}
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if "=" not in line or line.startswith("="):
                continue
            key, val = line.split("=", 1)
            if not re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", key):
                continue
            # `set` prints multi-line values across several physical lines;
            # keeping the first physical line would silently truncate a value.
            if key in pairs:
                pairs[key] = None          # mark as multi-line -> drop
                continue
            pairs[key] = val
    return pairs


def main():
    if len(sys.argv) < 5:
        print(__doc__)
        return 2
    dump, out, vsinst, msvc_ver = sys.argv[1:5]
    env = parse_dump(dump)

    sdk_bin = ""
    sdk_dir = env.get("WindowsSdkDir") or ""
    sdk_ver = env.get("WindowsSDKVersion") or ""
    if sdk_dir and sdk_ver:
        sdk_bin = sdk_dir.rstrip("\\/") + "\\bin\\" + sdk_ver.lstrip("\\/") + "\\x64"
    if not sdk_bin:
        sdk_bin = env.get("WindowsSdkBinPath") or env.get("WindowsSdkVerBinPath") or ""

    path_dirs = [
        vsinst + r"\VC\Tools\MSVC\%s\bin\HostX64\x64" % msvc_ver,
        sdk_bin,
        vsinst + r"\Common7\IDE\CommonExtensions\Microsoft\CMake\Ninja",
    ]
    path_dirs = [d for d in path_dirs if d]

    lines = [
        "# auto-generated MSVC environment snapshot -- do not edit by hand",
        "# regenerated by build.sh when the toolchain fingerprint changes",
    ]
    for key in KEEP:
        val = env.get(key)
        if val is None or val == "":
            continue
        val = val.replace("'", "'\"'\"'")
        lines.append("export %s='%s'" % (key, val))
    lines.append('export PATH="$PATH;' + ";".join(path_dirs) + '"')
    lines.append('export VSWHERE_MSVC_VER="%s"' % msvc_ver)

    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("[build] env snapshot: %s (%d vars)" % (out, len(lines) - 3))
    return 0


if __name__ == "__main__":
    sys.exit(main())
